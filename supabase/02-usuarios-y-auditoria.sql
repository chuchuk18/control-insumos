-- =====================================================================
--  Control de Insumos — Usuarios, auditoría e historial
--  Ejecutar después de schema.sql (SQL Editor → pegar todo → Run).
--  Se puede ejecutar más de una vez.
--
--  - perfiles: nombre visible y último acceso de cada usuario.
--  - Se registra QUIÉN dio de alta o editó cada insumo y qué cambió.
--  - Los consumos ya guardan qué usuario los cargó (usuario_id).
--  - v_historial: todo junto, para la pestaña Historial de la app.
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1. PERFILES (uno por usuario de Authentication)
-- ---------------------------------------------------------------------
create table if not exists public.perfiles (
  id             uuid primary key references auth.users(id) on delete cascade,
  email          text,
  nombre         text,
  ultimo_acceso  timestamptz,
  creado_en      timestamptz not null default now()
);

alter table public.perfiles enable row level security;
drop policy if exists "perfiles_leer"          on public.perfiles;
drop policy if exists "perfiles_editar_propio" on public.perfiles;
create policy "perfiles_leer"          on public.perfiles for select to authenticated using (true);
create policy "perfiles_editar_propio" on public.perfiles for update to authenticated
  using (id = auth.uid()) with check (id = auth.uid());
-- Cada uno solo puede cambiar su nombre y su último acceso (no el correo).
revoke all on public.perfiles from anon, authenticated;
grant select on public.perfiles to authenticated;
grant update (nombre, ultimo_acceso) on public.perfiles to authenticated;

-- Al crear un usuario en Authentication se crea su perfil automáticamente.
create or replace function public.crear_perfil()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.perfiles (id, email, nombre)
  values (new.id, new.email, nullif(trim(new.raw_user_meta_data ->> 'nombre'), ''))
  on conflict (id) do update set email = excluded.email;
  return new;
end;
$$;

drop trigger if exists al_crear_usuario on auth.users;
create trigger al_crear_usuario
  after insert or update of email on auth.users
  for each row execute function public.crear_perfil();

-- Perfiles para los usuarios que ya existían.
insert into public.perfiles (id, email)
select id, email from auth.users
on conflict (id) do update set email = excluded.email;

-- ---------------------------------------------------------------------
-- 2. QUIÉN CREÓ / MODIFICÓ CADA INSUMO
-- ---------------------------------------------------------------------
alter table public.insumos add column if not exists creado_por      uuid;
alter table public.insumos add column if not exists actualizado_por uuid;
alter table public.insumos add column if not exists actualizado_en  timestamptz;

create table if not exists public.auditoria (
  id           bigint generated by default as identity primary key,
  tabla        text not null,
  registro_id  bigint not null,
  accion       text not null check (accion in ('alta', 'edicion')),
  cambios      jsonb,                      -- {"campo": [antes, después], ...}
  usuario_id   uuid,
  fecha        timestamptz not null default now()
);
create index if not exists auditoria_fecha_idx    on public.auditoria (fecha desc);
create index if not exists auditoria_registro_idx on public.auditoria (tabla, registro_id);

-- La auditoría solo se lee; la escriben los triggers (nadie la puede editar ni borrar).
alter table public.auditoria enable row level security;
drop policy if exists "auditoria_leer" on public.auditoria;
create policy "auditoria_leer" on public.auditoria for select to authenticated using (true);
revoke all on public.auditoria from anon, authenticated;
grant select on public.auditoria to authenticated;

-- Antes de guardar: sella quién y cuándo (no se puede falsear desde la app).
create or replace function public.sellar_insumo()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if tg_op = 'INSERT' then
    new.creado_por := auth.uid();
  elsif coalesce(current_setting('insumos.por_consumo', true), '') <> 'si' then
    new.actualizado_por := auth.uid();
    new.actualizado_en  := now();
  end if;
  return new;
end;
$$;

drop trigger if exists trg_sellar_insumo on public.insumos;
create trigger trg_sellar_insumo
  before insert or update on public.insumos
  for each row execute function public.sellar_insumo();

-- Después de guardar: anota en auditoría qué cambió.
-- Los descuentos por consumo no se anotan acá (ya quedan en movimientos).
create or replace function public.auditar_insumo()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  campos  text[] := array['codigo', 'nombre', 'categoria', 'stock_actual', 'stock_minimo',
                          'unidad_medida', 'proveedor', 'ultimo_precio', 'fecha_ultimo_precio'];
  campo   text;
  antes   jsonb;
  despues jsonb;
  cambios jsonb := '{}'::jsonb;
begin
  if tg_op = 'INSERT' then
    insert into public.auditoria (tabla, registro_id, accion, cambios, usuario_id)
    values ('insumos', new.id, 'alta',
            jsonb_build_object('stock_actual', jsonb_build_array(null, new.stock_actual)), auth.uid());
    return new;
  end if;

  if coalesce(current_setting('insumos.por_consumo', true), '') = 'si' then
    return new;
  end if;

  antes := to_jsonb(old);
  despues := to_jsonb(new);
  foreach campo in array campos loop
    if (antes -> campo) is distinct from (despues -> campo) then
      cambios := cambios || jsonb_build_object(campo, jsonb_build_array(antes -> campo, despues -> campo));
    end if;
  end loop;

  if cambios <> '{}'::jsonb then
    insert into public.auditoria (tabla, registro_id, accion, cambios, usuario_id)
    values ('insumos', new.id, 'edicion', cambios, auth.uid());
  end if;
  return new;
end;
$$;

drop trigger if exists trg_auditar_insumo on public.insumos;
create trigger trg_auditar_insumo
  after insert or update on public.insumos
  for each row execute function public.auditar_insumo();

-- El descuento por consumo marca la operación para que no se audite como "edición".
create or replace function public.descontar_stock()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  perform set_config('insumos.por_consumo', 'si', true);
  update public.insumos
     set stock_actual = stock_actual - new.cantidad_retirada
   where id = new.insumo_id
     and stock_actual >= new.cantidad_retirada;

  if not found then
    perform set_config('insumos.por_consumo', '', true);
    if not exists (select 1 from public.insumos where id = new.insumo_id) then
      raise exception 'INSUMO_INEXISTENTE';
    end if;
    raise exception 'STOCK_INSUFICIENTE';
  end if;

  perform set_config('insumos.por_consumo', '', true);
  return new;
end;
$$;

-- El usuario de cada consumo lo pone la base (no se puede cargar a nombre de otro).
create or replace function public.sellar_movimiento()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.usuario_id := auth.uid();
  new.fecha_hora := now();
  return new;
end;
$$;

drop trigger if exists trg_sellar_movimiento on public.movimientos_insumos;
create trigger trg_sellar_movimiento
  before insert on public.movimientos_insumos
  for each row execute function public.sellar_movimiento();

-- ---------------------------------------------------------------------
-- 3. HISTORIAL (consumos + altas + ediciones, con nombre del usuario)
-- ---------------------------------------------------------------------
create or replace view public.v_historial
with (security_invoker = true) as
select 'consumo'::text           as tipo,
       m.fecha_hora              as fecha,
       m.insumo_id,
       i.nombre                  as insumo,
       i.codigo,
       i.unidad_medida,
       m.cantidad_retirada       as cantidad,
       m.practica_motivo         as motivo,
       m.responsable,
       null::jsonb               as cambios,
       m.usuario_id,
       coalesce(nullif(p.nombre, ''), p.email) as usuario
  from public.movimientos_insumos m
  join public.insumos i on i.id = m.insumo_id
  left join public.perfiles p on p.id = m.usuario_id
union all
select a.accion, a.fecha, a.registro_id, i.nombre, i.codigo, i.unidad_medida,
       null, null, null, a.cambios, a.usuario_id,
       coalesce(nullif(p.nombre, ''), p.email)
  from public.auditoria a
  join public.insumos i on i.id = a.registro_id
  left join public.perfiles p on p.id = a.usuario_id
 where a.tabla = 'insumos';

revoke all on public.v_historial from anon;
grant select on public.v_historial to authenticated;

-- ---------------------------------------------------------------------
-- 4. Estado de los usuarios (solo para revisar al ejecutar este script)
-- ---------------------------------------------------------------------
select u.email,
       (u.encrypted_password is not null and u.encrypted_password <> '') as tiene_contrasena,
       u.email_confirmed_at is not null                                  as correo_confirmado,
       u.invited_at is not null                                          as fue_invitado,
       u.last_sign_in_at                                                 as ultimo_ingreso
  from auth.users u
 order by u.created_at;
