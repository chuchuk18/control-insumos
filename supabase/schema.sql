-- ---------------------------------------------------------------------
-- 1. INSUMOS
-- ---------------------------------------------------------------------
create table if not exists public.insumos (
  id                  bigint generated by default as identity primary key,
  codigo              text,
  nombre              text not null check (length(trim(nombre)) > 0),
  categoria           text not null default 'General',
  stock_actual        numeric(14,3) not null default 0 check (stock_actual >= 0),
  stock_minimo        numeric(14,3) not null default 0 check (stock_minimo >= 0),
  unidad_medida       text not null default 'unidades',
  proveedor           text,
  ultimo_precio       numeric(14,4) check (ultimo_precio is null or ultimo_precio >= 0),  -- precio unitario
  fecha_ultimo_precio date,
  creado_en           timestamptz not null default now()
);

-- Nombre único sin distinguir mayúsculas; código único si se carga.
create unique index if not exists insumos_nombre_unico on public.insumos (lower(nombre));
create unique index if not exists insumos_codigo_unico on public.insumos (upper(codigo)) where codigo is not null;

-- ---------------------------------------------------------------------
-- 2. MOVIMIENTOS (consumos / bajas)
-- ---------------------------------------------------------------------
create table if not exists public.movimientos_insumos (
  id                 bigint generated by default as identity primary key,
  insumo_id          bigint not null references public.insumos(id) on delete restrict,
  cantidad_retirada  numeric(14,3) not null check (cantidad_retirada > 0),
  practica_motivo    text not null check (length(trim(practica_motivo)) > 0),
  responsable        text not null check (length(trim(responsable)) > 0),
  fecha_hora         timestamptz not null default now(),
  usuario_id         uuid default auth.uid()          -- usuario que lo registró
);
create index if not exists movimientos_insumo_idx on public.movimientos_insumos (insumo_id);
create index if not exists movimientos_fecha_idx  on public.movimientos_insumos (fecha_hora desc);

-- Regla: al registrar un retiro se descuenta del stock, en la misma
-- operación y sin permitir stock negativo (seguro aunque dos personas
-- retiren a la vez: la fila del insumo queda bloqueada durante el UPDATE).
create or replace function public.descontar_stock()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  update public.insumos
     set stock_actual = stock_actual - new.cantidad_retirada
   where id = new.insumo_id
     and stock_actual >= new.cantidad_retirada;

  if not found then
    if not exists (select 1 from public.insumos where id = new.insumo_id) then
      raise exception 'INSUMO_INEXISTENTE';
    end if;
    raise exception 'STOCK_INSUFICIENTE';
  end if;
  return new;
end;
$$;

drop trigger if exists trg_descontar_stock on public.movimientos_insumos;
create trigger trg_descontar_stock
  before insert on public.movimientos_insumos
  for each row execute function public.descontar_stock();

-- ---------------------------------------------------------------------
-- 3. VISTA DEL PANEL (estado del stock y valor)
--    security_invoker: respeta los permisos de quien consulta.
-- ---------------------------------------------------------------------
create or replace view public.v_insumos_estado
with (security_invoker = true) as
select i.*,
       case
         when i.stock_actual <= 0              then 'agotado'
         when i.stock_actual <= i.stock_minimo then 'bajo'
         else 'ok'
       end as estado_stock,
       round(i.stock_actual * i.ultimo_precio, 2) as valor_stock
  from public.insumos i;

-- ---------------------------------------------------------------------
-- 4. EQUIPOS y PRÉSTAMOS (módulo futuro)
-- ---------------------------------------------------------------------
create table if not exists public.equipos (
  id            bigint generated by default as identity primary key,
  codigo_serie  text not null unique,
  nombre        text not null,
  estado        text not null default 'Disponible'
                check (estado in ('Disponible', 'En uso', 'En mantenimiento'))
);

create table if not exists public.prestamos (
  id                   bigint generated by default as identity primary key,
  equipo_id            bigint not null references public.equipos(id) on delete restrict,
  usuario_responsable  text not null,
  fecha_retiro         timestamptz not null default now(),
  fecha_devolucion     timestamptz,
  estado               text not null default 'Activo' check (estado in ('Activo', 'Devuelto'))
);
-- Un equipo no puede tener dos préstamos activos a la vez.
create unique index if not exists prestamo_activo_unico on public.prestamos (equipo_id) where estado = 'Activo';

-- ---------------------------------------------------------------------
-- 5. SEGURIDAD (Row Level Security)
--    anon (sin sesión): sin acceso. authenticated: puede trabajar.
--    Los movimientos no se editan ni se borran (quedan como historial).
-- ---------------------------------------------------------------------
alter table public.insumos             enable row level security;
alter table public.movimientos_insumos enable row level security;
alter table public.equipos             enable row level security;
alter table public.prestamos           enable row level security;

drop policy if exists "insumos_leer"      on public.insumos;
drop policy if exists "insumos_alta"      on public.insumos;
drop policy if exists "insumos_editar"    on public.insumos;
create policy "insumos_leer"   on public.insumos for select to authenticated using (true);
create policy "insumos_alta"   on public.insumos for insert to authenticated with check (true);
create policy "insumos_editar" on public.insumos for update to authenticated using (true) with check (true);

drop policy if exists "movimientos_leer" on public.movimientos_insumos;
drop policy if exists "movimientos_alta" on public.movimientos_insumos;
create policy "movimientos_leer" on public.movimientos_insumos for select to authenticated using (true);
create policy "movimientos_alta" on public.movimientos_insumos for insert to authenticated
  with check (usuario_id is not distinct from auth.uid());

drop policy if exists "equipos_todo"   on public.equipos;
drop policy if exists "prestamos_todo" on public.prestamos;
create policy "equipos_todo"   on public.equipos   for all to authenticated using (true) with check (true);
create policy "prestamos_todo" on public.prestamos for all to authenticated using (true) with check (true);

-- Por las dudas, sin permisos para usuarios anónimos.
revoke all on public.insumos, public.movimientos_insumos, public.equipos, public.prestamos,
              public.v_insumos_estado from anon;

-- ---------------------------------------------------------------------
-- 6. TIEMPO REAL: avisar a todos los dispositivos cuando cambia algo.
-- ---------------------------------------------------------------------
do $$
declare t text;
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime') then
    foreach t in array array['insumos', 'movimientos_insumos'] loop
      if not exists (select 1 from pg_publication_tables
                      where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = t) then
        execute format('alter publication supabase_realtime add table public.%I', t);
      end if;
    end loop;
  end if;
end $$;
