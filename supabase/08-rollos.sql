-- =====================================================================
--  Control de Insumos — Seguimiento por rollo (film stretch, cintas)
--  Ejecutar después de 07-conjuntos.sql. Se puede repetir.
--
--  - Un insumo puede "controlarse por rollo": cada rollo tiene código y etiqueta QR.
--  - En el insumo se cargan el peso bruto de un rollo nuevo y el peso del cono vacío.
--    Si la unidad es kg, el contenido es el peso neto; si es otra (metros), se carga
--    el contenido por rollo y la base convierte peso → unidad.
--  - Cada rollo guarda su propia tara, factor y precio al recibirlo (cambiar los datos
--    del insumo después solo afecta a los rollos nuevos).
--  - Recibir rollos suma stock (entrada). Consumir = pesar el rollo después de la
--    práctica: la base calcula cuánto se usó y lo descuenta.
--  - El stock de un insumo por rollo es la suma de sus rollos: no se edita a mano.
-- =====================================================================

-- 1. Datos del rollo en el insumo
alter table public.insumos add column if not exists control_por_rollo   boolean not null default false;
alter table public.insumos add column if not exists tara_kg             numeric(10,3) check (tara_kg is null or tara_kg >= 0);
alter table public.insumos add column if not exists peso_bruto_rollo_kg numeric(10,3) check (peso_bruto_rollo_kg is null or peso_bruto_rollo_kg > 0);
alter table public.insumos add column if not exists contenido_por_rollo numeric(14,3) check (contenido_por_rollo is null or contenido_por_rollo > 0);

-- 2. Rollos
create table if not exists public.rollos (
  id               bigint generated by default as identity primary key,
  insumo_id        bigint not null references public.insumos(id) on delete restrict,
  codigo           text not null,
  peso_inicial_kg  numeric(10,3) not null check (peso_inicial_kg > 0),
  peso_actual_kg   numeric(10,3) not null check (peso_actual_kg >= 0),
  tara_kg          numeric(10,3) not null check (tara_kg >= 0),
  factor           numeric(16,6) not null check (factor > 0),          -- unidades del insumo por kg neto
  precio           numeric(14,2) check (precio is null or precio >= 0), -- precio del rollo completo
  estado           text not null default 'Nuevo' check (estado in ('Nuevo', 'En uso', 'Terminado')),
  saldo            numeric(14,3) generated always as (
                     case when estado = 'Terminado' then 0
                          else round(greatest(peso_actual_kg - tara_kg, 0) * factor, 3) end) stored,
  recibido_en      timestamptz not null default now(),
  ultimo_uso       timestamptz,
  terminado_en     timestamptz,
  creado_por       uuid default auth.uid()
);
create unique index if not exists rollos_codigo_unico on public.rollos (upper(codigo));
create index if not exists rollos_insumo_idx on public.rollos (insumo_id, estado);

alter table public.rollos enable row level security;
drop policy if exists "rollos_leer"   on public.rollos;
drop policy if exists "rollos_alta"   on public.rollos;
drop policy if exists "rollos_editar" on public.rollos;
create policy "rollos_leer"   on public.rollos for select to authenticated using (true);
create policy "rollos_alta"   on public.rollos for insert to authenticated with check (true);
create policy "rollos_editar" on public.rollos for update to authenticated using (true) with check (true);
revoke all on public.rollos from anon, authenticated;
grant select on public.rollos to authenticated;
grant insert (insumo_id, codigo, peso_inicial_kg, precio) on public.rollos to authenticated;
grant update (codigo) on public.rollos to authenticated;

-- 3. Consumo por rollo
alter table public.movimientos_insumos add column if not exists rollo_id        bigint references public.rollos(id) on delete restrict;
alter table public.movimientos_insumos add column if not exists peso_antes_kg   numeric(10,3);
alter table public.movimientos_insumos add column if not exists peso_despues_kg numeric(10,3);
alter table public.movimientos_insumos add column if not exists cerrar_rollo    boolean not null default false;
create index if not exists movimientos_rollo_idx on public.movimientos_insumos (rollo_id);

-- 4. Stock de insumos por rollo: solo lo cambian los rollos y los consumos.
create or replace function public.stock_por_rollos()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if coalesce(current_setting('insumos.por_consumo', true), '') = 'si' then
    return new;
  end if;
  if tg_op = 'INSERT' then
    if new.control_por_rollo then
      new.stock_actual := 0;
    end if;
    return new;
  end if;
  if new.control_por_rollo and not old.control_por_rollo then
    -- Pasa a controlarse por rollo: el stock se arma con los rollos que se registren.
    new.stock_actual := coalesce((select sum(saldo) from public.rollos where insumo_id = new.id), 0);
  elsif new.control_por_rollo and new.stock_actual is distinct from old.stock_actual then
    raise exception 'STOCK_POR_ROLLOS';
  end if;
  return new;
end;
$$;

drop trigger if exists trg_rollos_stock on public.insumos;
create trigger trg_rollos_stock
  before insert or update on public.insumos
  for each row execute function public.stock_por_rollos();

-- 5. Recibir un rollo: toma tara y factor del insumo, genera el código y suma stock.
create or replace function public.preparar_rollo()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  i      public.insumos%rowtype;
  n      int;
  prefijo text;
begin
  select * into i from public.insumos where id = new.insumo_id for update;
  if not found then
    raise exception 'INSUMO_INEXISTENTE';
  end if;
  if not i.control_por_rollo then
    raise exception 'INSUMO_SIN_ROLLOS';
  end if;
  if i.tara_kg is null then
    raise exception 'FALTA_TARA';
  end if;
  if i.contenido_por_rollo is not null and (i.peso_bruto_rollo_kg is null or i.peso_bruto_rollo_kg <= i.tara_kg) then
    raise exception 'FALTA_PESO_BRUTO';
  end if;

  new.peso_inicial_kg := coalesce(new.peso_inicial_kg, i.peso_bruto_rollo_kg);
  if new.peso_inicial_kg is null or new.peso_inicial_kg <= i.tara_kg then
    raise exception 'PESO_ROLLO_INVALIDO';
  end if;

  new.tara_kg        := i.tara_kg;
  new.factor         := case when i.contenido_por_rollo is null then 1
                             else i.contenido_por_rollo / (i.peso_bruto_rollo_kg - i.tara_kg) end;
  new.peso_actual_kg := new.peso_inicial_kg;
  new.estado         := 'Nuevo';
  new.recibido_en    := now();
  new.ultimo_uso     := null;
  new.terminado_en   := null;
  new.creado_por     := auth.uid();

  if length(trim(coalesce(new.codigo, ''))) = 0 then
    prefijo := coalesce(nullif(upper(trim(i.codigo)), ''), 'INS' || i.id);
    n := (select count(*) from public.rollos where insumo_id = i.id);
    loop
      n := n + 1;
      new.codigo := prefijo || '-R' || lpad(n::text, 3, '0');
      exit when not exists (select 1 from public.rollos where upper(codigo) = upper(new.codigo));
    end loop;
  else
    new.codigo := upper(trim(new.codigo));
  end if;
  return new;
end;
$$;

drop trigger if exists trg_preparar_rollo on public.rollos;
create trigger trg_preparar_rollo
  before insert on public.rollos
  for each row execute function public.preparar_rollo();

create or replace function public.entrada_rollo()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  contenido numeric := round((new.peso_inicial_kg - new.tara_kg) * new.factor, 3);
begin
  perform set_config('insumos.por_consumo', 'si', true);
  update public.insumos
     set stock_actual = stock_actual + contenido,
         ultimo_precio = case when new.precio is not null and contenido > 0 then round(new.precio / contenido, 4) else ultimo_precio end,
         fecha_ultimo_precio = case when new.precio is not null then current_date else fecha_ultimo_precio end
   where id = new.insumo_id;
  perform set_config('insumos.por_consumo', '', true);
  return new;
end;
$$;

drop trigger if exists trg_entrada_rollo on public.rollos;
create trigger trg_entrada_rollo
  after insert on public.rollos
  for each row execute function public.entrada_rollo();

-- 6. Consumo por pesada: corre antes de descontar el stock (por eso el nombre "trg_a_…").
create or replace function public.consumo_por_rollo()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  r          public.rollos%rowtype;
  saldo_desp numeric;
  cantidad   numeric;
  cerrar     boolean := coalesce(new.cerrar_rollo, false);
begin
  if new.rollo_id is null then
    if exists (select 1 from public.insumos where id = new.insumo_id and control_por_rollo) then
      raise exception 'FALTA_ROLLO';
    end if;
    new.peso_antes_kg := null;
    new.peso_despues_kg := null;
    new.cerrar_rollo := false;
    return new;
  end if;

  select * into r from public.rollos where id = new.rollo_id for update;
  if not found or r.insumo_id <> new.insumo_id then
    raise exception 'ROLLO_INVALIDO';
  end if;
  if r.estado = 'Terminado' then
    raise exception 'ROLLO_TERMINADO';
  end if;

  new.peso_antes_kg := r.peso_actual_kg;
  if new.peso_despues_kg is null and not cerrar then
    raise exception 'FALTA_PESO';
  end if;
  if new.peso_despues_kg is not null then
    if new.peso_despues_kg > r.peso_actual_kg then
      raise exception 'PESO_MAYOR:%', r.peso_actual_kg;
    end if;
    if new.peso_despues_kg < r.tara_kg - 0.05 then
      raise exception 'PESO_MENOR_TARA:%', r.tara_kg;
    end if;
  end if;

  if cerrar then
    cantidad := r.saldo;   -- lo que quedaba se da por usado o descartado
    new.peso_despues_kg := coalesce(new.peso_despues_kg, r.tara_kg);
  else
    saldo_desp := round(greatest(new.peso_despues_kg - r.tara_kg, 0) * r.factor, 3);
    cantidad := r.saldo - saldo_desp;
    cerrar := saldo_desp <= 0;
  end if;
  if cantidad <= 0 then
    raise exception 'SIN_CONSUMO';
  end if;
  -- Redondeos: nunca descontar más de lo que hay.
  cantidad := least(cantidad, (select stock_actual from public.insumos where id = new.insumo_id));
  new.cantidad_retirada := cantidad;
  new.cerrar_rollo := cerrar;

  update public.rollos
     set peso_actual_kg = coalesce(new.peso_despues_kg, r.tara_kg),
         estado = case when cerrar then 'Terminado' else 'En uso' end,
         ultimo_uso = now(),
         terminado_en = case when cerrar then now() end
   where id = r.id;
  return new;
end;
$$;

drop trigger if exists trg_a_consumo_rollo on public.movimientos_insumos;
create trigger trg_a_consumo_rollo
  before insert on public.movimientos_insumos
  for each row execute function public.consumo_por_rollo();

-- Precio del consumo: el del rollo usado (precio del rollo / contenido), si no el del insumo.
create or replace function public.sellar_movimiento()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.usuario_id := auth.uid();
  new.fecha_hora := now();
  new.precio_unitario := coalesce(
    (select round(r.precio / nullif(round((r.peso_inicial_kg - r.tara_kg) * r.factor, 3), 0), 4)
       from public.rollos r where r.id = new.rollo_id),
    (select ultimo_precio from public.insumos where id = new.insumo_id));
  return new;
end;
$$;

-- 7. Auditoría del insumo: también los datos del rollo
create or replace function public.auditar_insumo()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  campos  text[] := array['codigo', 'nombre', 'categoria', 'stock_actual', 'stock_minimo',
                          'unidad_medida', 'proveedor', 'ultimo_precio', 'fecha_ultimo_precio',
                          'control_por_rollo', 'tara_kg', 'peso_bruto_rollo_kg', 'contenido_por_rollo'];
  campo   text;
  antes   jsonb;
  despues jsonb;
  cambios jsonb := '{}'::jsonb;
begin
  if tg_op = 'INSERT' then
    insert into public.auditoria (tabla, registro_id, accion, cambios, usuario_id)
    values ('insumos', new.id, 'alta',
            jsonb_build_object('stock_actual', jsonb_build_array(null, new.stock_actual)), auth.uid());
    return new;
  end if;

  if coalesce(current_setting('insumos.por_consumo', true), '') = 'si' then
    return new;
  end if;

  antes := to_jsonb(old);
  despues := to_jsonb(new);
  foreach campo in array campos loop
    if (antes -> campo) is distinct from (despues -> campo) then
      cambios := cambios || jsonb_build_object(campo, jsonb_build_array(antes -> campo, despues -> campo));
    end if;
  end loop;

  if cambios <> '{}'::jsonb then
    insert into public.auditoria (tabla, registro_id, accion, cambios, usuario_id)
    values ('insumos', new.id, 'edicion', cambios, auth.uid());
  end if;
  return new;
end;
$$;

-- 8. Vistas
drop view if exists public.v_rollos;
create view public.v_rollos
with (security_invoker = true) as
select r.*,
       i.nombre        as insumo,
       i.codigo        as insumo_codigo,
       i.categoria,
       i.unidad_medida,
       round((r.peso_inicial_kg - r.tara_kg) * r.factor, 3) as contenido_inicial,
       (select count(*) from public.movimientos_insumos m where m.rollo_id = r.id)::int as usos,
       coalesce(nullif(pf.nombre, ''), pf.email) as recibido_por
  from public.rollos r
  join public.insumos i on i.id = r.insumo_id
  left join public.perfiles pf on pf.id = r.creado_por;
revoke all on public.v_rollos from anon;
grant select on public.v_rollos to authenticated;

drop view if exists public.v_insumos_estado;
create view public.v_insumos_estado
with (security_invoker = true) as
select i.*,
       case
         when i.stock_actual <= 0              then 'agotado'
         when i.stock_actual <= i.stock_minimo then 'bajo'
         else 'ok'
       end as estado_stock,
       round(i.stock_actual * i.ultimo_precio, 2) as valor_stock,
       (select count(*) from public.rollos r where r.insumo_id = i.id and r.estado <> 'Terminado')::int as rollos_activos,
       (select count(*) from public.rollos r where r.insumo_id = i.id and r.estado = 'En uso')::int as rollos_en_uso
  from public.insumos i;
revoke all on public.v_insumos_estado from anon;
grant select on public.v_insumos_estado to authenticated;

drop view if exists public.v_consumos;
create view public.v_consumos
with (security_invoker = true) as
select m.id,
       m.fecha_hora,
       (m.fecha_hora at time zone 'America/Montevideo')::date as dia,
       m.insumo_id,
       i.codigo,
       i.nombre              as insumo,
       i.categoria,
       i.unidad_medida,
       i.proveedor,
       m.cantidad_retirada   as cantidad,
       m.precio_unitario,
       round(m.cantidad_retirada * m.precio_unitario, 2) as costo,
       m.practica_motivo,
       m.responsable,
       m.usuario_id,
       coalesce(nullif(pf.nombre, ''), pf.email) as registrado_por,
       r.codigo              as rollo_codigo,
       m.peso_antes_kg,
       m.peso_despues_kg
  from public.movimientos_insumos m
  join public.insumos i on i.id = m.insumo_id
  left join public.rollos r on r.id = m.rollo_id
  left join public.perfiles pf on pf.id = m.usuario_id;
revoke all on public.v_consumos from anon;
grant select on public.v_consumos to authenticated;

drop view if exists public.v_historial;
create view public.v_historial
with (security_invoker = true) as
select 'insumos'::text  as modulo, 'consumo'::text as tipo, m.fecha_hora as fecha,
       m.insumo_id as item_id, i.nombre as item, i.codigo, i.unidad_medida,
       m.cantidad_retirada as cantidad, m.practica_motivo as motivo, m.responsable,
       null::jsonb as cambios,
       case when m.rollo_id is not null then
         'Rollo ' || r.codigo || ' · ' || replace(to_char(m.peso_antes_kg, 'FM999990.000'), '.', ',') || ' → ' ||
         replace(to_char(coalesce(m.peso_despues_kg, r.tara_kg), 'FM999990.000'), '.', ',') || ' kg' ||
         case when m.cerrar_rollo then ' · rollo terminado' else '' end
       end as detalle,
       m.usuario_id,
       coalesce(nullif(pf.nombre, ''), pf.email) as usuario
  from public.movimientos_insumos m
  join public.insumos i on i.id = m.insumo_id
  left join public.rollos r on r.id = m.rollo_id
  left join public.perfiles pf on pf.id = m.usuario_id
union all
select 'insumos', 'entrada', r.recibido_en, r.insumo_id, i.nombre, i.codigo, i.unidad_medida,
       round((r.peso_inicial_kg - r.tara_kg) * r.factor, 3), 'Rollo ' || r.codigo, null, null,
       concat_ws(' · ', 'Peso bruto ' || replace(to_char(r.peso_inicial_kg, 'FM999990.000'), '.', ',') || ' kg',
                 case when r.precio is not null then '$ ' || replace(to_char(r.precio, 'FM999999990.00'), '.', ',') end),
       r.creado_por, coalesce(nullif(pf.nombre, ''), pf.email)
  from public.rollos r
  join public.insumos i on i.id = r.insumo_id
  left join public.perfiles pf on pf.id = r.creado_por
union all
select 'insumos', a.accion, a.fecha, a.registro_id, i.nombre, i.codigo, i.unidad_medida,
       null, null, null, a.cambios, null, a.usuario_id, coalesce(nullif(pf.nombre, ''), pf.email)
  from public.auditoria a
  join public.insumos i on i.id = a.registro_id
  left join public.perfiles pf on pf.id = a.usuario_id
 where a.tabla = 'insumos'
union all
select 'equipos', a.accion, a.fecha, a.registro_id, e.nombre, e.codigo_serie, null,
       null, null, null, a.cambios, null, a.usuario_id, coalesce(nullif(pf.nombre, ''), pf.email)
  from public.auditoria a
  join public.equipos e on e.id = a.registro_id
  left join public.perfiles pf on pf.id = a.usuario_id
 where a.tabla = 'equipos'
union all
select 'equipos', 'prestamo', p.fecha_retiro, p.equipo_id, e.nombre, e.codigo_serie, null,
       null, p.practica_motivo, p.usuario_responsable, null,
       concat_ws(' · ',
         case when p.fecha_prevista is not null then 'Devolución prevista: ' || to_char(p.fecha_prevista, 'DD/MM/YYYY') end,
         case when e.es_conjunto then 'Conjunto con ' || (select count(*) from public.equipos c where c.conjunto_id = e.id) || ' componentes' end),
       p.registrado_por, coalesce(nullif(pf.nombre, ''), pf.email)
  from public.prestamos p
  join public.equipos e on e.id = p.equipo_id
  left join public.perfiles pf on pf.id = p.registrado_por
union all
select 'equipos', 'devolucion', p.fecha_devolucion, p.equipo_id, e.nombre, e.codigo_serie, null,
       null, null, p.usuario_responsable, null,
       concat_ws(' · ',
         p.condicion_devolucion,
         'Con novedad: ' || (select string_agg(c.nombre, ', ' order by c.nombre) from public.equipos c where c.id = any(p.componentes_con_novedad)),
         nullif(trim(p.observaciones_devolucion), '')),
       p.recibido_por, coalesce(nullif(pf.nombre, ''), pf.email)
  from public.prestamos p
  join public.equipos e on e.id = p.equipo_id
  left join public.perfiles pf on pf.id = p.recibido_por
 where p.estado = 'Devuelto';
revoke all on public.v_historial from anon;
grant select on public.v_historial to authenticated;

