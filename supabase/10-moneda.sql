-- =====================================================================
--  Control de Insumos — Moneda: pesos uruguayos ($) y dólares (US$)
--  Ejecutar después de 09-alarma-quiebre.sql. Se puede repetir.
--
--  - Cada precio guarda su moneda: precio del insumo, precio de cada rollo y valor del equipo.
--  - tipos_cambio: historial de cotizaciones (1 US$ = X $), cargadas en la app.
--  - Cada consumo guarda el precio y la moneda originales y el tipo de cambio del día;
--    su costo queda en $ y se puede ver en US$ con ese mismo tipo de cambio,
--    así los costos pasados no cambian cuando se mueve el dólar.
--  - Si un precio está en US$ y todavía no hay tipo de cambio cargado, el consumo queda sin costo.
-- =====================================================================

-- 1. Tipo de cambio (historial)
create table if not exists public.tipos_cambio (
  id         bigint generated by default as identity primary key,
  fecha      date not null default ((now() at time zone 'America/Montevideo')::date),
  usd_uyu    numeric(10,4) not null check (usd_uyu > 0),
  fuente     text,
  creado_por uuid default auth.uid(),
  creado_en  timestamptz not null default now()
);
create index if not exists tipos_cambio_fecha_idx on public.tipos_cambio (fecha desc, id desc);

alter table public.tipos_cambio enable row level security;
drop policy if exists "tc_leer" on public.tipos_cambio;
drop policy if exists "tc_alta" on public.tipos_cambio;
create policy "tc_leer" on public.tipos_cambio for select to authenticated using (true);
create policy "tc_alta" on public.tipos_cambio for insert to authenticated with check (true);
revoke all on public.tipos_cambio from anon, authenticated;
grant select on public.tipos_cambio to authenticated;
grant insert (fecha, usd_uyu, fuente) on public.tipos_cambio to authenticated;

create or replace function public.sellar_tipo_cambio()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.creado_por := auth.uid();
  new.creado_en := now();
  if new.fecha > (now() at time zone 'America/Montevideo')::date then
    raise exception 'FECHA_FUTURA';
  end if;
  return new;
end;
$$;
drop trigger if exists trg_sellar_tipo_cambio on public.tipos_cambio;
create trigger trg_sellar_tipo_cambio
  before insert on public.tipos_cambio
  for each row execute function public.sellar_tipo_cambio();

-- Cotización vigente: la de fecha más reciente.
create or replace function public.tipo_cambio_actual()
returns numeric
language sql
stable
set search_path = public
as $$
  select usd_uyu from public.tipos_cambio order by fecha desc, id desc limit 1;
$$;

-- 2. Moneda de cada precio
alter table public.insumos add column if not exists moneda_precio text not null default 'UYU' check (moneda_precio in ('UYU', 'USD'));
alter table public.equipos add column if not exists moneda_valor  text not null default 'UYU' check (moneda_valor in ('UYU', 'USD'));
alter table public.rollos  add column if not exists moneda        text not null default 'UYU' check (moneda in ('UYU', 'USD'));
grant insert (insumo_id, codigo, peso_inicial_kg, precio, moneda) on public.rollos to authenticated;

alter table public.movimientos_insumos add column if not exists precio_original numeric(14,4);
alter table public.movimientos_insumos add column if not exists moneda_precio   text check (moneda_precio is null or moneda_precio in ('UYU', 'USD'));
alter table public.movimientos_insumos add column if not exists tipo_cambio     numeric(10,4);

-- 3. Consumo: precio y moneda originales + tipo de cambio del día; precio_unitario queda en $.
create or replace function public.sellar_movimiento()
returns trigger
language plpgsql
set search_path = public
as $$
declare
  po  numeric;
  mon text;
  tc  numeric := public.tipo_cambio_actual();
begin
  new.usuario_id := auth.uid();
  new.fecha_hora := now();
  if new.rollo_id is not null then
    select round(r.precio / nullif(round((r.peso_inicial_kg - r.tara_kg) * r.factor, 3), 0), 4), r.moneda
      into po, mon
      from public.rollos r where r.id = new.rollo_id;
  end if;
  if po is null then
    select ultimo_precio, moneda_precio into po, mon from public.insumos where id = new.insumo_id;
  end if;
  new.precio_original := po;
  new.moneda_precio   := case when po is null then null else coalesce(mon, 'UYU') end;
  new.tipo_cambio     := tc;
  new.precio_unitario := case
    when po is null then null
    when coalesce(mon, 'UYU') = 'USD' then case when tc is null then null else round(po * tc, 4) end
    else po
  end;
  return new;
end;
$$;

-- Consumos anteriores: su precio era en $.
update public.movimientos_insumos
   set moneda_precio = 'UYU', precio_original = precio_unitario
 where moneda_precio is null and precio_unitario is not null;

-- 4. Recibir rollos: el precio del insumo queda en la moneda del rollo.
create or replace function public.entrada_rollo()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  contenido numeric := round((new.peso_inicial_kg - new.tara_kg) * new.factor, 3);
begin
  perform set_config('insumos.por_consumo', 'si', true);
  update public.insumos
     set stock_actual = stock_actual + contenido,
         ultimo_precio = case when new.precio is not null and contenido > 0 then round(new.precio / contenido, 4) else ultimo_precio end,
         fecha_ultimo_precio = case when new.precio is not null then current_date else fecha_ultimo_precio end,
         moneda_precio = case when new.precio is not null then new.moneda else moneda_precio end
   where id = new.insumo_id;
  perform set_config('insumos.por_consumo', '', true);
  return new;
end;
$$;

-- 5. Auditoría: también la moneda
create or replace function public.auditar_insumo()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  campos  text[] := array['codigo', 'nombre', 'categoria', 'stock_actual', 'stock_minimo',
                          'unidad_medida', 'proveedor', 'ultimo_precio', 'fecha_ultimo_precio',
                          'control_por_rollo', 'tara_kg', 'peso_bruto_rollo_kg', 'contenido_por_rollo', 'unidad_referencia',
                          'consumo_semanal_manual', 'fuente_promedio', 'plazo_reposicion_dias', 'dias_seguridad',
                          'moneda_precio'];
  campo   text;
  antes   jsonb;
  despues jsonb;
  cambios jsonb := '{}'::jsonb;
begin
  if tg_op = 'INSERT' then
    insert into public.auditoria (tabla, registro_id, accion, cambios, usuario_id)
    values ('insumos', new.id, 'alta',
            jsonb_build_object('stock_actual', jsonb_build_array(null, new.stock_actual)), auth.uid());
    return new;
  end if;

  if coalesce(current_setting('insumos.por_consumo', true), '') = 'si' then
    return new;
  end if;

  antes := to_jsonb(old);
  despues := to_jsonb(new);
  foreach campo in array campos loop
    if (antes -> campo) is distinct from (despues -> campo) then
      cambios := cambios || jsonb_build_object(campo, jsonb_build_array(antes -> campo, despues -> campo));
    end if;
  end loop;

  if cambios <> '{}'::jsonb then
    insert into public.auditoria (tabla, registro_id, accion, cambios, usuario_id)
    values ('insumos', new.id, 'edicion', cambios, auth.uid());
  end if;
  return new;
end;
$$;

